def cow_diagnostics(I: float) -> str:
    """
    Диагностика датчика ДТК75 и коровы сибирской степной породы по току датчика.

    Формула пересчёта сигнал-значение:
        PV = (I - i_min) * (PV_max - PV_min) / (i_max - i_min) + PV_min

    PV     – текущее значение температуры, °C;
    I      – значение выходного сигнала датчика, мА;
    PV_min – минимальное значение диапазона (0 °C);
    PV_max – максимальное значение диапазона (75 °C);
    i_min, i_max – токи, соответствующие PV_min и PV_max (4 и 20 мА).

    Диагностика датчика:
        I == 0               – датчик отключён;
        0 < I < 3.9          – датчик неисправен;
        3.9 <= I <= 20.1     – датчик исправен (значение достоверно);
        I > 20.1             – датчик неисправен.

    Диагностика коровы (норма 37.5…39.0 °C):
        PV > 39.6            – срочно вызывайте ветеринара, коровка заболела;
        PV < 34.9            – требуется внимание (датчик свалился или корова плохо себя чувствует);
        35.0 <= PV < 37.4    – корова замёрзла, требуется обогрев;
        37.5 <= PV <= 39.0   – с коровой всё ок;
        39.1 < PV < 39.5     – корова перегрелась, требуется охлаждение.
    """
    PV_min, PV_max = 0.0, 75.0        # диапазон измерения датчика, °C
    i_min, i_max = 4.0, 20.0          # границы токовой петли, мА
    i_ok_low, i_ok_high = 3.9, 20.1   # границы достоверности сигнала, мА

    try:
        # 1. Тип входа: bool отсекаем отдельно, он подкласс int
        if type(I) not in (int, float):
            raise TypeError(f"'I' должен быть числом")

        # 2. Значение
        if I < 0:
            raise ValueError(f"отрицательный ток: {I}")

        # 3. Диагностика датчика
        if I == 0:
            return (f"Получен сигнал датчика {I:.2f} мА, датчик отключён, ")
        if not i_ok_low <= I <= i_ok_high:
            return (f"Получен сигнал датчика {I:.2f} мА, датчик неисправен, ")

        # 4. Вычислеения
        PV = (I - i_min) * (PV_max - PV_min) / (i_max - i_min) + PV_min

        # 5. Диапазон
        PV = float(min(max(PV, PV_min), PV_max))

        # 6. Диагностика коровы
        if PV > 39.6:
            cow = "срочно вызывайте ветеринара, коровка заболела"
        elif PV < 34.9:
            cow = "корова умеерла?"
        elif PV < 37.4:
            cow = "корова замёрзла, требуется обогрев"
        elif PV <= 39.0:
            cow = "с коровой всё ок"
        else:
            cow = "корова перегрелась, требуется охлаждение"

        return (f"температура {PV:.2f} градусов, {cow}")

    except (TypeError, ValueError) as error:
        return f"Ошибка входных данных — {error}"



for i in range(-2, 50):
    print(cow_diagnostics(i / 2))
